import 'package:intl/intl.dart';

/// English and German text. `tr('key', {'name': 'Lina'})` fills `{name}`.
/// Keys ending in `_one` / `_other` are picked with [plural].
class L10n {
  L10n(this.lang);
  final String lang;

  String get locale => lang == 'de' ? 'de_DE' : 'en_GB';

  String tr(String key, [Map<String, Object> params = const {}]) {
    var s = (lang == 'de' ? _de[key] : null) ?? _en[key] ?? key;
    params.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  String plural(String key, num count, [Map<String, Object> params = const {}]) => tr(count == 1 ? '${key}_one' : '${key}_other', {'count': _num(count), ...params});

  String _num(num n) => n % 1 == 0 ? '${n.toInt()}' : NumberFormat('0.#', locale).format(n);
  String hours(num h) => '${_num(h)} h';
  String money(num v, [String currency = 'EUR']) => NumberFormat.simpleCurrency(locale: locale, name: currency, decimalDigits: v % 1 == 0 ? 0 : 2).format(v);
  String day(DateTime d) => DateFormat(lang == 'de' ? 'EEE, d. MMM' : 'EEE d MMM', locale).format(d);
  String dayLong(DateTime d) => DateFormat(lang == 'de' ? 'EEEE, d. MMMM' : 'EEEE d MMMM', locale).format(d);
  String weekdayShort(DateTime d) => DateFormat('EEE', locale).format(d);
  String time(DateTime d) => DateFormat('HH:mm', locale).format(d);
  String monthYear(DateTime d) => DateFormat('MMMM yyyy', locale).format(d);
  String range(DateTime a, DateTime b) => '${DateFormat(lang == 'de' ? 'd. MMM' : 'd MMM', locale).format(a)} – ${DateFormat(lang == 'de' ? 'd. MMM' : 'd MMM', locale).format(b)}';
}

